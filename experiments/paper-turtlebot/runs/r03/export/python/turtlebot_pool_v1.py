    ga = numpy.float64(0.7100507251393503)  # fitted, unit -
    coupling = numpy.float64(0.3616404487941903)  # fitted, unit s/m
    with numpy.errstate(all="ignore"):
        _x_next = (x + (Ts * gf * v_f * numpy.cos(phi)))
        _y_next = (y + (Ts * gf * v_f * numpy.sin(phi)))
        _phi_next = (phi + (Ts * v_a * (ga + (coupling * v_f))))
    return {'x_next': numpy.broadcast_to(numpy.asarray(_x_next, dtype=float), _shape).copy(), 'y_next': numpy.broadcast_to(numpy.asarray(_y_next, dtype=float), _shape).copy(), 'phi_next': numpy.broadcast_to(numpy.asarray(_phi_next, dtype=float), _shape).copy()}


