def SpeedTurnCoupling(x, y, phi, v_f, v_a):
    """Candidate SpeedTurnCoupling: returns {'x_next', 'y_next', 'phi_next'} as NumPy arrays of the broadcast shape of the arguments. Arguments in the units of VARIABLES."""
    x = numpy.asarray(x, dtype=float)
    y = numpy.asarray(y, dtype=float)
    phi = numpy.asarray(phi, dtype=float)
    v_f = numpy.asarray(v_f, dtype=float)
    v_a = numpy.asarray(v_a, dtype=float)
    _shape = numpy.broadcast_shapes(numpy.shape(x), numpy.shape(y), numpy.shape(phi), numpy.shape(v_f), numpy.shape(v_a))
    Ts = numpy.float64(0.2)  # fixed, unit s
